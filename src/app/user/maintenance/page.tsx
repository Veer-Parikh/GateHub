const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);

/** Opens a print-ready receipt in a new tab (users can save it as PDF from the print dialog). */
function openReceipt(b: MaintenanceBill, r: Resident) {
  const rows = b.breakdown.map((l) => `<tr><td>${esc(l.label)}</td><td class="r">${inr(l.amount)}</td></tr>`).join("");
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>Receipt ${esc(b.billId)}</title>
<style>body{font:14px/1.5 system-ui,sans-serif;color:#18181b;max-width:640px;margin:40px auto;padding:0 24px}
h1{font-size:20px;margin:0}small{color:#71717a}table{width:100%;border-collapse:collapse;margin:20px 0}
td,th{padding:8px 0;border-bottom:1px solid #e4e4e7;text-align:left}.r{text-align:right}
.tot td{font-weight:700;border-bottom:2px solid #18181b}.paid{display:inline-block;padding:2px 10px;border:1px solid #16a34a;color:#16a34a;border-radius:99px;font-size:12px;font-weight:600}
.grid{display:grid;grid-template-columns:1fr 1fr;gap:4px 24px;margin-top:20px}button{margin-top:24px;padding:8px 16px}@media print{button{display:none}}</style></head>
<body><h1>${esc(r.society)}</h1><small>Maintenance receipt · generated by NexGate</small>
<div class="grid"><div><small>Receipt no.</small><br>REC-${esc(b.billId.toUpperCase())}</div><div><small>Status</small><br><span class="paid">PAID</span></div>
<div><small>Flat</small><br>Tower ${esc(b.block)}, Flat ${esc(b.flat)}</div><div><small>Resident</small><br>${esc(b.residentName)}</div>
<div><small>Billing period</small><br>${esc(b.month)} ${b.year}</div><div><small>Paid on</small><br>${b.paidAt ? format(new Date(b.paidAt), "d MMM yyyy, h:mm a") : "—"}</div>
<div><small>Method</small><br>${esc(b.method ?? "—")}</div><div><small>Transaction ID</small><br>${esc(b.txnId ?? "—")}</div></div>
<table><tr><th>Item</th><th class="r">Amount</th></tr>${rows}<tr class="tot"><td>Total paid</td><td class="r">${inr(b.amount)}</td></tr></table>
<small>This is a computer-generated receipt and does not need a signature.</small><br><button onclick="print()">Print / save as PDF</button></body></html>`;
  const url = URL.createObjectURL(new Blob([html], { type: "text/html" }));
  const win = window.open(url, "_blank", "noopener");
  if (!win) {
    const a = document.createElement("a");
    a.href = url;
    a.download = `Receipt-${b.month}-${b.year}.html`;
    a.click();
  }
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
}

function exportCsv(bills: MaintenanceBill[]) {
  const header = ["Tower", "Flat", "Resident", "Phone", "Period", "Amount", "Status", "Paid on", "Method"];
  const lines = bills.map((b) =>
    [b.block, b.flat, b.residentName, b.phone, `${b.month} ${b.year}`, b.amount, b.paidAt ? "Paid" : "Unpaid", b.paidAt ? format(new Date(b.paidAt), "yyyy-MM-dd") : "", b.method ?? ""]
      .map((v) => `"${String(v).replace(/"/g, '""')}"`)
      .join(","),
  );
  const url = URL.createObjectURL(new Blob([[header.join(","), ...lines].join("\n")], { type: "text/csv" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = `maintenance-ledger-${format(new Date(), "yyyy-MM-dd")}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

